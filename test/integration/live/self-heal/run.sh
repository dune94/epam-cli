#!/usr/bin/env bash
# SELF-HEAL, FUNCTIONALLY, ON LIVE TOKENS — the pipeline's own components, called as the attempt loop calls them.
#
#   run.sh <work-dir>
#
# A real brownfield repository whose greetings table is compiled to source by `npm run generate` (its README says to run
# it after cloning; the output is not committed). The baseline does not use the generated module, so the baseline suite
# is green; the story's change — correct — reads it, so on a fresh checkout its suite fails until the environment runs
# the generator. The attempt loop then does exactly this, and so does this harness — pipeline code only, nothing
# stubbed, every agent on the live copilot set:
#   0. the analyst's project prompt is built from the current template, as a run's start builds it
#   1. run_external_verification  — the suite fails on what the story changed
#   2. run_failure_analyst        — diagnoses the failure and applies its remedy
#   3. run_external_verification  — the next attempt's verification (it runs any repair the heal sanctioned first)
# Self-heal works when step 3 passes. Prints RESULT lines; exit 0 always (the caller judges).
set -uo pipefail
W="${1:?work dir}"; rm -rf "$W"; mkdir -p "$W"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; REPO_ROOT="$(cd "$HERE/../../../.." && pwd)"
ORCH="$REPO_ROOT/orchestrations"; NODE="${NODE_BIN:-$(command -v node)}"

# ── the codeline: the seed project, plus a greetings table compiled to source by `npm run generate` ──
# The generated module is not committed (as generated code usually is not); the README says to generate it after
# cloning. The baseline does not use it, so the baseline suite is green. The story's change — correct — reads the
# table, so on a fresh checkout its suite fails until the environment runs the generator.
R="$W/codeline"; cp -a "$ORCH/projects/hello-dolly/seed" "$R"
ln -s "$REPO_ROOT/node_modules" "$R/node_modules"
mkdir -p "$R/scripts"
printf '{ "hello": "hello there" }\n' > "$R/greetings.json"
cat > "$R/scripts/generate.mjs" <<'JS'
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
const table = JSON.parse(readFileSync(new URL('../greetings.json', import.meta.url), 'utf8'));
mkdirSync(new URL('../src/generated/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/generated/greetings.ts', import.meta.url),
  `// GENERATED by scripts/generate.mjs from greetings.json — do not edit.\nexport const GREETINGS = ${JSON.stringify(table)} as const;\n`);
console.log('generated src/generated/greetings.ts');
JS
"$NODE" -e '
const fs=require("fs");const p=process.argv[1];const j=JSON.parse(fs.readFileSync(p,"utf8"));
j.scripts.generate="node scripts/generate.mjs";fs.writeFileSync(p,JSON.stringify(j,null,2)+"\n");' "$R/package.json"
printf 'src/generated/\n' >> "$R/.gitignore"
printf '# hello\n\nGreetings live in `greetings.json` and are compiled to `src/generated/` (not committed).\nAfter cloning, and after editing `greetings.json`, run `npm run generate`.\n' > "$R/README.md"
git -C "$R" init -q -b develop; git -C "$R" add -A
git -C "$R" -c user.email=t@t -c user.name=t commit -qm base
BASE=$(git -C "$R" rev-parse HEAD)
git -C "$R" checkout -q -b bugfix/AI-S-1
# The story's change — correct, and its test.
printf "import { GREETINGS } from './generated/greetings';\n\nexport function getGreeting(): string {\n  return GREETINGS.hello;\n}\n" > "$R/src/hello.ts"
cat >> "$R/src/greeting.test.ts" <<'TS'

describe('the greeting the story asks for', () => {
  it('is the hello entry of the greetings table', () => { expect(getGreeting()).toBe('hello there'); });
});
TS
git -C "$R" add -A; git -C "$R" -c user.email=t@t -c user.name=t commit -qm "S-1: story complete"

# ── the project and the run's state, as the pipeline keeps them ──
# The project config a live run generated (its prompts are built at run start, from the engine of that install).
SRC_PROJECT="${SELF_HEAL_PROJECT:-$(ls -t "$HOME"/projects/tests/installs/*/orchestrations/projects/metrolinx/prompts/failure-analyst.json 2>/dev/null | head -1 | xargs -r dirname | xargs -r dirname)}"
[ -f "$SRC_PROJECT/prompts/failure-analyst.json" ] || { echo "RESULT setup=no generated project prompts at '$SRC_PROJECT'"; exit 0; }
echo "RESULT project=$SRC_PROJECT"
P="$W/project"; cp -r "$SRC_PROJECT" "$P"; chmod -R u+w "$P"; rm -rf "$P/runs" "$P/kb"
# metrolinx's verification overrides describe ITS jest suites, not this codeline; detection decides here.
rm -f "$P/verification.json" "$P/codeline-facts.json" "$P/prd.json"
L="$W/logs"; mkdir -p "$L"; printf '%s\n' "$BASE" > "$L/phase-baseline-sha.txt"
PRD="$W/prd.json"
cat > "$PRD" <<JSON
{"project":{"name":"hello","outputDir":"$R","outputDirs":[{"codeline":"hello","path":"$R"}]},
 "implementationOrder":{"core":["S-1"]},
 "stories":[{"id":"S-1","phase":"core","codeline":"hello","agentRole":"toast-messaging-engineer","title":"The greeting says hello there",
   "description":"getGreeting() must return the 'hello' entry of the greetings table (greetings.json, compiled to src/generated/ by npm run generate).","status":"in-progress","completed":false,
   "acceptanceCriteria":["getGreeting() returns the greetings table's 'hello' entry","the project's test suite passes"],
   "technicalNotes":{"files":["src/hello.ts","src/greeting.test.ts"]}}]}
JSON

# ── the pipeline's own functions, loaded as claude.sh loads them ──
export SCRIPT_DIR="$ORCH/scripts" AUTOMATION_DIR="$ORCH" NODE_BIN="$NODE"
export PROJECT_ROOT="$R" OUTPUT_DIR="$R" PRD_FILE="$PRD" MAIN_PRD_FILE="$PRD" LOG_DIR="$L" PHASE=core
export EPAM_PROJECT_CONFIG_DIR="$P" EPAM_BROWNFIELD=1 JIRA_BASELINE_BRANCH=develop EPAM_CODELINE=hello
export EPAM_PROVIDER_SET=copilot
export COPILOT_GITHUB_TOKEN="$("$NODE" -e 'const s=require("fs").readFileSync(process.env.HOME+"/.copilot/config.json","utf8").split("\n").filter(l=>!/^\s*\/\//.test(l)).join("\n");process.stdout.write(JSON.parse(s).copilotTokens["https://github.com:dune94"]||"")')"
cd "$R"
# The project's env, as orchestrate.sh loads it (base + the active set's overlay).
. "$SCRIPT_DIR/lib/env-file.sh"; load_project_env "$P" || { echo "RESULT setup=project env failed"; exit 0; }
# shellcheck source=/dev/null
. "$SCRIPT_DIR/claude.sh"
set +e
# The codeline's .epam/, as the pipeline provisions every codeline (verification manifest from the repo's own scripts).
_provision_epam_plugin_config "$R"
echo "RESULT verification_manifest=$([ -f "$R/.epam/verification.json" ] && tr -d '\n' < "$R/.epam/verification.json" | cut -c1-300 || echo none)"
echo "RESULT gate_provider=${ORCH_GATE_PROVIDER:-<none>}"

# The analyst's project prompt from the CURRENT template, as a run's start builds it (live generator).
"$NODE" "$HERE/rebuild-analyst-prompt.js" "$P" "$L" hello "$R" > "$L/prompt-rebuild.json" 2> "$L/prompt-rebuild.log"
echo "RESULT prompt_rebuild_rc=$? $(cat "$L/prompt-rebuild.json" 2>/dev/null)"
echo "RESULT analyst_prompt_env_rule=$("$NODE" -e 'const b=String(require(process.argv[1]).body||"");const l=b.split("\n").find(x=>/target=environment:/.test(x))||"";process.stdout.write(/tool_spec/.test(l)?"names tool_spec":"NO tool_spec in its environment rule")' "$P/prompts/failure-analyst.json")"

OUT="$L/attempt.log"; : > "$OUT"
run_external_verification S-1 "$OUT"; v1=$?
printf '%s' "${VERIFICATION_FAILURE:-}" > "$L/verification-1.txt"
echo "RESULT verify1=$v1"
run_failure_analyst S-1 "$OUT" 1; a=$?
echo "RESULT analyst_rc=$a"
tail -1 "$L/healing-events.jsonl" 2>/dev/null | "$NODE" -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{const e=JSON.parse(s);console.log("RESULT heal_target="+(e.target||"")+" | "+String(e.diagnosis||"").slice(0,200).replace(/\n/g," "))}catch{console.log("RESULT heal_target=<none recorded>")}})'
VERIFICATION_FAILURE=""
run_external_verification S-1 "$OUT"; v2=$?
echo "RESULT verify2=$v2"
echo "RESULT generated=$([ -f "$R/src/generated/greetings.ts" ] && echo yes || echo no)"
echo "RESULT dynamic_tools=$(ls "$R/.epam/dynamic-tools" 2>/dev/null | tr '\n' ' ')"
exit 0
