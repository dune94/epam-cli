/**
 * A COMMIT INSIDE A PIPELINE WORKTREE IS NOT REFUSED BY THE CODELINE'S OWN HOOKS.
 *
 * Real-estate rehearsal, 2026-10-05 (a copy of next.gotransit.com): core.hooksPath=.husky, and its
 * pre-commit sources .husky/_/husky.sh — generated, untracked, so absent from every new worktree — and
 * refuses any branch outside ^(feature|bugfix|…)/…, which `wt-primary` is. The pipeline's story commit
 * failed in the worktree and Step 17 reported "nothing to merge": the writer's work silently dropped.
 * The live writer had got past the same hook only by running `git commit --no-verify` itself.
 *
 * Operator decision: the pipeline's own commits INSIDE a worktree do not run the hooks; what lands on
 * the story branch still does (the Step 17 merge runs commit-msg in the checkout). This repo is built as
 * that codeline is: the same hooksPath shape, a helper the checkout has and a worktree does not, and a
 * pre-commit that refuses the worktree's branch. EXECUTED: the real commit_completed_story.
 */
import { describe, it, expect, afterAll } from 'vitest';
import { spawnSync, execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, chmodSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const SCRIPTS = join(__dirname, '../../../orchestrations/scripts');
const root = mkdtempSync(join(tmpdir(), 'wt-hooks-'));
afterAll(() => rmSync(root, { recursive: true, force: true }));
const git = (cwd: string, ...a: string[]) => execFileSync('git', a, { cwd, encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@t', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@t' } }).trim();

function codeline() {
  const repo = join(root, `cl-${Math.random().toString(36).slice(2, 8)}`);
  mkdirSync(join(repo, '.husky', '_'), { recursive: true });
  git(root, 'init', '-q', '-b', 'develop', repo);
  writeFileSync(join(repo, '.gitignore'), '.husky/_\n');
  writeFileSync(join(repo, '.husky', '_', 'husky.sh'), '# generated by the tool, never tracked\n');
  writeFileSync(join(repo, '.husky', 'pre-commit'), [
    '#!/bin/bash', '. "$(dirname "$0")/_/husky.sh"',
    'b="$(git rev-parse --abbrev-ref HEAD)"',
    '[[ $b =~ ^(feature|bugfix|tech|release|hotfix)/[a-zA-Z0-9.-]+$ ]] || { echo "branch $b refused"; exit 1; }', '',
  ].join('\n'));
  chmodSync(join(repo, '.husky', 'pre-commit'), 0o755);
  writeFileSync(join(repo, 'a.txt'), 'a\n');
  git(repo, 'add', '-A'); git(repo, 'commit', '-q', '--no-verify', '-m', 'baseline');
  git(repo, 'config', 'core.hooksPath', '.husky');
  git(repo, 'checkout', '-q', '-b', 'bugfix/AI-T-1');
  const wt = join(root, `${repo.split('/').pop()}-wt-primary`);
  git(repo, 'worktree', 'add', '-q', '-b', 'wt-primary', wt, 'HEAD');
  return { repo, wt };
}

function commitStory(at: string) {
  writeFileSync(join(at, 'a.txt'), `changed ${Date.now()}\n`);
  return spawnSync('bash', ['-c', [
    'log(){ :; }; warning(){ echo "WARN $*" >&2; }; error(){ echo "ERR $*" >&2; }; success(){ :; }; info(){ :; }',
    `source ${JSON.stringify(join(SCRIPTS, 'lib/git-ops.sh'))} >/dev/null 2>&1`,
    `PROJECT_ROOT=${JSON.stringify(at)} LOG_DIR=${JSON.stringify(root)} commit_completed_story T-1`,
  ].join('\n')], { encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@t', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@t' } });
}

describe('the pipeline commits a story inside a worktree of a codeline whose hooks refuse it', () => {
  it('in the worktree: the story commit lands', () => {
    const { wt } = codeline();
    const before = git(wt, 'rev-parse', 'HEAD');
    const r = commitStory(wt);
    expect(git(wt, 'rev-parse', 'HEAD'), `no commit in the worktree:\n${r.stdout}\n${r.stderr}`).not.toBe(before);
    expect(git(wt, 'log', '-1', '--format=%s')).toMatch(/^T-1: story complete/);
  });

  it('work left uncommitted in a worktree is named, never read as "nothing to merge"', () => {
    const { wt } = codeline();
    const dirty = (at: string) => spawnSync('bash', ['-c', `log(){ :; }; warning(){ :; }; error(){ :; }; source ${JSON.stringify(join(SCRIPTS, 'lib/git-ops.sh'))} >/dev/null 2>&1; worktree_uncommitted_work ${JSON.stringify(at)}`], { encoding: 'utf8' }).stdout.trim();
    expect(dirty(wt), 'a clean worktree reported work').toBe('');
    writeFileSync(join(wt, 'a.txt'), 'the writer changed this\n');
    mkdirSync(join(wt, '.epam'), { recursive: true }); writeFileSync(join(wt, '.epam', 'x.json'), '{}');
    expect(dirty(wt)).toBe('a.txt');
  });

  // Operator decision, 2026-10-05 (second): the checkout too — next.gotransit.com's hook fails its own
  // untouched checkout (a whole-project type check its team's node_modules cannot pass), so it refused
  // every pipeline commit there, whatever it held.
  it('in the checkout: a hook that refuses everything does not refuse the pipeline\'s commit', () => {
    const { repo } = codeline();
    writeFileSync(join(repo, '.husky', 'pre-commit'), '#!/bin/bash\necho "refused by the codeline"; exit 1\n');
    const before = git(repo, 'rev-parse', 'HEAD');
    const plain = spawnSync('git', ['commit', '--allow-empty', '-m', 'plain'], { cwd: repo, encoding: 'utf8' });
    expect(plain.status, 'the hook did not refuse a plain commit — the test proves nothing').not.toBe(0);
    const r = commitStory(repo);
    expect(git(repo, 'rev-parse', 'HEAD'), `the pipeline's commit was refused:\n${r.stdout}\n${r.stderr}`).not.toBe(before);
  });
});
